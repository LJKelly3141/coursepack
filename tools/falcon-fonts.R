# Build falcon-fonts.scss for the falcon and falcon-light slide styles.
#
# The fonts are embedded as data URIs so a deck rendered with
# embed-resources: true needs no web access and looks the same on every
# machine. Sources: tools/falcon-fonts/, from the @fontsource npm packages
# (barlow-condensed 5.3.0, nunito-sans 5.3.0), latin subset, both under the
# SIL Open Font License 1.1. The licence texts are copied beside the styles.
#
# Run from the package root: Rscript tools/falcon-fonts.R

src <- "tools/falcon-fonts"
faces <- list(
  list("Barlow Condensed", 600, "normal", "barlow-condensed-latin-600-normal.woff2"),
  list("Nunito Sans", 400, "normal", "nunito-sans-latin-400-normal.woff2"),
  list("Nunito Sans", 400, "italic", "nunito-sans-latin-400-italic.woff2"),
  list("Nunito Sans", 700, "normal", "nunito-sans-latin-700-normal.woff2"),
  list("Nunito Sans", 700, "italic", "nunito-sans-latin-700-italic.woff2"))

b64 <- function(path) {
  raw <- readBin(path, "raw", file.size(path))
  # base64_enc() wraps its output; a CSS string cannot span lines.
  gsub("[\r\n]", "", jsonlite::base64_enc(raw))
}

out <- c("/*-- scss:defaults --*/", "",
         "// Generated by tools/falcon-fonts.R; do not edit by hand.",
         "// Barlow Condensed and Nunito Sans, SIL Open Font License 1.1",
         "// (OFL-BarlowCondensed.txt, OFL-NunitoSans.txt beside this file).", "",
         "/*-- scss:rules --*/", "")
for (f in faces) {
  out <- c(out, "@font-face {",
           sprintf("  font-family: \"%s\";", f[[1]]),
           sprintf("  font-weight: %d;", f[[2]]),
           sprintf("  font-style: %s;", f[[3]]),
           "  font-display: swap;",
           sprintf("  src: url(\"data:font/woff2;base64,%s\") format(\"woff2\");", b64(file.path(src, f[[4]]))),
           "}", "")
}

for (style in c("falcon", "falcon-light")) {
  dst <- file.path("inst/templates/slides/_extensions", style)
  writeLines(out, file.path(dst, "falcon-fonts.scss"), useBytes = TRUE)
  file.copy(file.path(src, "barlow-condensed-LICENSE.txt"), file.path(dst, "OFL-BarlowCondensed.txt"), overwrite = TRUE)
  file.copy(file.path(src, "nunito-sans-LICENSE.txt"), file.path(dst, "OFL-NunitoSans.txt"), overwrite = TRUE)
  cat("wrote", file.path(dst, "falcon-fonts.scss"), "\n")
}
